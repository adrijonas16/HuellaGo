// Fechas relativas a hoy para que el prototipo siempre muestre eventos futuros
function upcoming(days: number, time = '10:00'): string {
  const d = new Date();
  d.setDate(d.getDate() + days);
  const pad = (n: number) => String(n).padStart(2, '0');
  return `${d.getFullYear()}-${pad(d.getMonth() + 1)}-${pad(d.getDate())}T${time}:00`;
}

